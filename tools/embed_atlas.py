"""Turn an atlas file into a C++ source that defines globe::kEmbeddedAtlasData/Size.

    embed_atlas.py data/atlas.gatl OUT.cpp

Deterministic (no timestamps). The generated file is a build artifact; do not commit it.
"""
import sys


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__)
    with open(argv[0], "rb") as f:
        data = f.read()
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02X" % b for b in data[i : i + 24]) + ",")
    with open(argv[1], "w") as out:
        out.write("// Generated by tools/embed_atlas.py from %s. Do not edit.\n" % argv[0].split("/")[-1])
        out.write('#include "globe/embedded_atlas.hpp"\n\nnamespace globe {\n\n')
        out.write("const std::uint8_t kEmbeddedAtlasData[] = {\n")
        out.write("\n".join(lines) + "\n};\n\n")
        out.write("const std::size_t kEmbeddedAtlasSize = %d;\n\n} // namespace globe\n" % len(data))


if __name__ == "__main__":
    main(sys.argv[1:])
