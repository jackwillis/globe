"""Embed an atlas (default) or elevation file as a C++ resource.

    embed_atlas.py data/atlas.gatl OUT.cpp [Atlas|Elevation]

Deterministic (no timestamps). The generated file is a build artifact; do not commit it.
"""
import sys


def main(argv):
    if len(argv) not in (2, 3):
        sys.exit(__doc__)
    kind = argv[2] if len(argv) == 3 else "Atlas"
    if kind not in ("Atlas", "Elevation"):
        sys.exit("resource kind must be Atlas or Elevation")
    with open(argv[0], "rb") as f:
        data = f.read()
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02X" % b for b in data[i : i + 24]) + ",")
    with open(argv[1], "w") as out:
        out.write("// Generated by tools/embed_atlas.py from %s. Do not edit.\n" % argv[0].split("/")[-1])
        out.write('#include "globe/embedded_%s.hpp"\n\nnamespace globe {\n\n' % kind.lower())
        out.write("const std::uint8_t kEmbedded%sData[] = {\n" % kind)
        out.write("\n".join(lines) + "\n};\n\n")
        out.write("const std::size_t kEmbedded%sSize = %d;\n\n} // namespace globe\n" % (kind, len(data)))


if __name__ == "__main__":
    main(sys.argv[1:])
