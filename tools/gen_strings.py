"""Generates the committed string tables from l10n/*.txt (no build-time Python needed by
cross builds). `--check` verifies the committed files are current and every language is complete."""
import sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
langs = ["en", "es"]  # order of globe::Language

def load(code):
    out = {}
    for n, line in enumerate((root / "l10n" / f"{code}.txt").read_text().splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        key, sep, text = line.partition(" = ")
        if not sep or not key.isidentifier():
            sys.exit(f"{code}.txt:{n}: expected 'Key = text'")
        if key in out:
            sys.exit(f"{code}.txt:{n}: duplicate key {key}")
        out[key] = text
        if not text.isascii() or '"' in text or "\\" in text:
            sys.exit(f"{code}.txt:{n}: ASCII only, no quotes or backslashes")
    return out

tables = {c: load(c) for c in langs}
keys = list(tables["en"])
for c in langs:
    if list(tables[c]) != keys:
        sys.exit(f"{c}.txt: keys differ from en.txt (same keys, same order required)")
hdr = "// Generated by tools/gen_strings.py from l10n/*.txt. Do not edit.\n"
files = {"include/globe/strings_keys.inc": hdr + "".join(f"GLOBE_STR({k})\n" for k in keys)}
for c in langs:
    files[f"src/core/strings_{c}.inc"] = hdr + "".join(f'"{t}",\n' for t in tables[c].values())
bad = 0
for rel, text in files.items():
    path = root / rel
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != text:
            print(f"stale: {rel}"); bad = 1
    else:
        path.write_text(text)
sys.exit(bad)
